/**
 * Asset Enqueue
 *
 * Handles CSS and JavaScript loading for the theme.
 *
 * @package    gCube
 * @subpackage Assets
 * @since      2.0.0
 *
 * @dependencies constants.php (GCUBE_DIR, GCUBE_URI)
 * @dependents   None (registers WordPress hooks)
 *
 * @hooks
 *   - wp_enqueue_scripts: gcube_enqueue_assets()
 *
 * CSS Architecture (SRP-based modules):
 * - main.css: Aggregator that @imports all module files
 * - variables.css: CSS custom properties
 * - cube-structure.css: 3D transforms, positioning
 * - cube-surfaces.css: Dual-surface pseudo-elements
 * - face-content.css: Content containers, scrolling
 * - face-expansion.css: Fullscreen reading mode
 * - navigation.css: Nav buttons, wrappers
 * - typography.css: Fonts, text styles
 * - content-types.css: Posts, slugs, glass mode
 * - responsive.css: Media queries
 */

if (!defined('ABSPATH')) {
    exit;
}

/**
 * Enqueue theme styles and scripts
 *
 * @since 1.0.0
 * @return void
 */
function gcube_enqueue_assets(): void {
    $theme_uri = GCUBE_URI;
    $theme_dir = GCUBE_DIR;
    $version = GCUBE_VERSION;

    // Built CSS: gCube's modules in one file (no @import waterfall), generated by
    // scripts/build-css.sh; main.css @imports in dev. gTemplate's stylesheets stay
    // enqueued by gTemplate and load first.
    $built_css_path = $theme_dir . '/assets/css/gcube.built.css';
    $parent_css = ['gtemplate-fonts', 'gtemplate-golden-typography', 'gtemplate-geodineum-content'];

    if (file_exists($built_css_path)) {
        wp_enqueue_style(
            'gcube-built-css',
            $theme_uri . '/assets/css/gcube.built.css',
            $parent_css,
            filemtime($built_css_path)
        );
    } else {
        // Dev mode: use @imports (slower on mobile, easier to debug)
        $main_css_path = $theme_dir . '/assets/css/main.css';
        $css_version = file_exists($main_css_path) ? filemtime($main_css_path) : $version;

        wp_enqueue_style(
            'gcube-main-css',
            $theme_uri . '/assets/css/main.css',
            $parent_css,
            $css_version
        );
    }

    // Enqueue cube controls JavaScript (CRITICAL for rotation/interaction)
    wp_enqueue_script(
        'gcube-cube-controls',
        $theme_uri . '/assets/js/cube-controls.js',
        [],
        (string) (@filemtime($theme_dir . '/assets/js/cube-controls.js') ?: $version),
        ['in_footer' => true, 'strategy' => 'defer']
    );

    // Pass customizer settings to JavaScript for expansion feature
    wp_localize_script('gcube-cube-controls', 'gcubeSettings', gcube_get_js_settings());

    // Dequeue parent's PWA loader (gCube has its own)
    wp_dequeue_script('gtemplate-pwa-loader');

    // Enqueue PWA loader
    wp_enqueue_script(
        'gcube-pwa-loader',
        $theme_uri . '/assets/js/pwa-loader.js',
        [],
        (string) (@filemtime($theme_dir . '/assets/js/pwa-loader.js') ?: $version),
        ['in_footer' => true, 'strategy' => 'defer']
    );
}
// Priority 20: after the parent's enqueue (priority 10), which registers the parent CSS handles
add_action('wp_enqueue_scripts', 'gcube_enqueue_assets', 20);

/**
 * Light/dark toggle is not ready on the cube yet. Runs at wp_head:2, right after
 * the parent's pre-paint boot (wp_head:1): overrides any persisted light choice
 * back to the brand dark ground (no flash) and sets data-geo-no-theme-toggle so
 * the parent geo-behaviors.js skips mounting the floating toggle.
 */
function gcube_lock_dark_theme(): void {
    echo '<script>(function(){var r=document.documentElement;r.setAttribute("data-theme","dark");r.setAttribute("data-geo-no-theme-toggle","");})();</script>' . "\n";
}
add_action('wp_head', 'gcube_lock_dark_theme', 2);

/**
 * Get JavaScript settings from Customizer
 *
 * @since 2.0.0
 * @return array Settings for wp_localize_script
 */
function gcube_get_js_settings(): array {
    // gtemplate_expand_* are the parent-registered settings (the old
    // gcube_expand_* reads pointed at names nothing registers)
    return [
        'expandMode' => get_theme_mod('gtemplate_expand_mode', 'focus'),
        'expandEnabled' => (bool) get_theme_mod('gtemplate_expand_enabled', true),
        'showCloseButton' => (bool) get_theme_mod('gtemplate_expand_show_close', true),
        'showHint' => (bool) get_theme_mod('gtemplate_expand_show_hint', true),
    ];
}

/**
 * Glass box: the splat renderer (three.js + Spark under assets/lib, imported by relative path, so no
 * import map) loads only on sites with a splat set, after page load.
 */
function gcube_splat_box_url(): string {
    return trim((string) gcube_mod('cube_splat_url'));
}

function gcube_enqueue_splat_box(): void {
    if (gcube_splat_box_url() === '' || !function_exists('wp_register_script_module')) {
        return;
    }
    $file = GCUBE_DIR . '/assets/js/splat-box.js';
    wp_enqueue_script_module('gcube-splat-box', GCUBE_URI . '/assets/js/splat-box.js', [], (string) (@filemtime($file) ?: GCUBE_VERSION));
}
add_action('wp_enqueue_scripts', 'gcube_enqueue_splat_box', 30);

function gcube_print_splat_box_config(): void {
    $url = gcube_splat_box_url();
    if ($url === '') {
        return;
    }
    $config = [
        'url' => esc_url_raw($url),
        'flip' => (bool) gcube_mod('cube_splat_flip'),
        'spin' => (int) gcube_mod('cube_splat_spin'),
        'credit' => (string) gcube_mod('cube_splat_credit'),
        'creditUrl' => esc_url_raw((string) gcube_mod('cube_splat_credit_url')),
    ];
    echo '<script type="application/json" id="gcube-splat-box">' . wp_json_encode($config, JSON_UNESCAPED_SLASHES | JSON_HEX_TAG) . "</script>\n";
}
add_action('wp_footer', 'gcube_print_splat_box_config', 5);

// The renderer compiles WebAssembly and starts workers from data: URLs.
add_filter('gtemplate_csp_script_src', static function (array $src): array {
    return gcube_splat_box_url() === '' ? $src : [...$src, "'wasm-unsafe-eval'"];
});
add_filter('gtemplate_csp_worker_src', static function (array $src): array {
    return gcube_splat_box_url() === '' ? $src : [...$src, "'self'", 'data:', 'blob:'];
});

// Splat captures can go in the Media Library (product pictures in the glass box).
add_filter('upload_mimes', static function (array $mimes): array {
    foreach (['splat', 'spz', 'ksplat', 'ply'] as $ext) {
        $mimes[$ext] = 'application/octet-stream';
    }
    return $mimes;
});
add_filter('wp_check_filetype_and_ext', static function (array $data, $file, $filename): array {
    $ext = strtolower(pathinfo((string) $filename, PATHINFO_EXTENSION));
    if (in_array($ext, ['splat', 'spz', 'ksplat', 'ply'], true) && current_user_can('upload_files')) {
        $data['ext'] = $ext;
        $data['type'] = 'application/octet-stream';
        $data['proper_filename'] = false;
    }
    return $data;
}, 10, 3);
